package googleadk

// Surface-drift guard for the replay-safe telemetry wrappers. The wrappers
// embed the OTel interface they wrap, so any method they do not explicitly
// declare is promoted from the embedded inner value and delegates UNGATED.
// OTel Go deliberately grows these interfaces without a major version bump
// (see the "API Implementations" notice in the trace/metric/log package docs
// and the embedded.* types), so a routine dependency bump can add an emitting
// method — e.g. the sync instruments' Enabled(ctx) — that silently bypasses
// the replay gate. TestReplaySafeWrapperSurface fails loudly on any promoted
// method that has not been explicitly audited, forcing a decision: gate it,
// or allowlist it here with the reason delegation is correct.

import (
	"context"
	"reflect"
	"runtime"
	"strings"
	"testing"

	"github.com/stretchr/testify/require"

	otellog "go.opentelemetry.io/otel/log"
	lognoop "go.opentelemetry.io/otel/log/noop"
	"go.opentelemetry.io/otel/metric"
	metricnoop "go.opentelemetry.io/otel/metric/noop"
	"go.opentelemetry.io/otel/trace"
	tracenoop "go.opentelemetry.io/otel/trace/noop"
)

// inheritedInterfaceMethods returns the exported methods of iface that wrapper
// satisfies through promotion from its embedded field rather than an explicit
// declaration. Promoted methods are compiler-generated forwarding thunks and
// report "<autogenerated>" as their source file; declared methods report the
// real one. Unexported interface methods (the otel embedded.* growth markers)
// are skipped: they cannot be declared outside their package.
func inheritedInterfaceMethods(t *testing.T, iface reflect.Type, wrapper any) []string {
	t.Helper()
	wrapperType := reflect.TypeOf(wrapper)
	require.Truef(t, wrapperType.Implements(iface),
		"%v does not implement %v; the audit table is wired to the wrong pair", wrapperType, iface)
	var inherited []string
	for i := 0; i < iface.NumMethod(); i++ {
		im := iface.Method(i)
		if !im.IsExported() {
			continue
		}
		wm, ok := wrapperType.MethodByName(im.Name)
		require.Truef(t, ok, "%v implements %v but lacks method %s", wrapperType, iface, im.Name)
		pc := wm.Func.Pointer()
		file, _ := runtime.FuncForPC(pc).FileLine(pc)
		if strings.Contains(file, "<autogenerated>") {
			inherited = append(inherited, im.Name)
		}
	}
	return inherited
}

func typeOf[T any]() reflect.Type { return reflect.TypeOf((*T)(nil)).Elem() }

// TestReplaySafeWrapperSurface audits every wrapper against the interface it
// wraps at the currently-pinned OTel version. It fails when an interface
// method is neither declared on the wrapper nor allowlisted as intentionally
// delegated, and when an allowlist entry goes stale (method removed upstream
// or now declared).
func TestReplaySafeWrapperSurface(t *testing.T) {
	const observableRationale = "observable instruments record via reader collect-cycle callbacks that never run under a workflow context"

	innerMeter := replaySafeMeter{Meter: metricnoop.NewMeterProvider().Meter("audit")}
	instrument := func(v any, err error) any {
		require.NoError(t, err)
		return v
	}

	cases := []struct {
		name    string
		iface   reflect.Type
		wrapper any
		// delegated lists interface methods intentionally satisfied by
		// promotion, each with the rationale that makes delegation safe.
		delegated map[string]string
	}{
		{
			name:    "TracerProvider",
			iface:   typeOf[trace.TracerProvider](),
			wrapper: NewReplaySafeTracerProvider(tracenoop.NewTracerProvider()),
		},
		{
			name:    "Tracer",
			iface:   typeOf[trace.Tracer](),
			wrapper: NewReplaySafeTracerProvider(tracenoop.NewTracerProvider()).Tracer("audit"),
		},
		{
			name:    "LoggerProvider",
			iface:   typeOf[otellog.LoggerProvider](),
			wrapper: NewReplaySafeLoggerProvider(lognoop.NewLoggerProvider()),
		},
		{
			name:    "Logger",
			iface:   typeOf[otellog.Logger](),
			wrapper: NewReplaySafeLoggerProvider(lognoop.NewLoggerProvider()).Logger("audit"),
		},
		{
			name:    "MeterProvider",
			iface:   typeOf[metric.MeterProvider](),
			wrapper: NewReplaySafeMeterProvider(metricnoop.NewMeterProvider()),
		},
		{
			name:    "Meter",
			iface:   typeOf[metric.Meter](),
			wrapper: innerMeter,
			delegated: map[string]string{
				"Int64ObservableCounter":         observableRationale,
				"Int64ObservableUpDownCounter":   observableRationale,
				"Int64ObservableGauge":           observableRationale,
				"Float64ObservableCounter":       observableRationale,
				"Float64ObservableUpDownCounter": observableRationale,
				"Float64ObservableGauge":         observableRationale,
				"RegisterCallback":               "registration must reach the inner meter so it accepts the inner meter's own observables; callbacks never run under a workflow context",
			},
		},
		{
			name:    "Int64Counter",
			iface:   typeOf[metric.Int64Counter](),
			wrapper: instrument(innerMeter.Int64Counter("audit")),
		},
		{
			name:    "Int64UpDownCounter",
			iface:   typeOf[metric.Int64UpDownCounter](),
			wrapper: instrument(innerMeter.Int64UpDownCounter("audit")),
		},
		{
			name:    "Int64Histogram",
			iface:   typeOf[metric.Int64Histogram](),
			wrapper: instrument(innerMeter.Int64Histogram("audit")),
		},
		{
			name:    "Int64Gauge",
			iface:   typeOf[metric.Int64Gauge](),
			wrapper: instrument(innerMeter.Int64Gauge("audit")),
		},
		{
			name:    "Float64Counter",
			iface:   typeOf[metric.Float64Counter](),
			wrapper: instrument(innerMeter.Float64Counter("audit")),
		},
		{
			name:    "Float64UpDownCounter",
			iface:   typeOf[metric.Float64UpDownCounter](),
			wrapper: instrument(innerMeter.Float64UpDownCounter("audit")),
		},
		{
			name:    "Float64Histogram",
			iface:   typeOf[metric.Float64Histogram](),
			wrapper: instrument(innerMeter.Float64Histogram("audit")),
		},
		{
			name:    "Float64Gauge",
			iface:   typeOf[metric.Float64Gauge](),
			wrapper: instrument(innerMeter.Float64Gauge("audit")),
		},
	}

	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			inherited := inheritedInterfaceMethods(t, tc.iface, tc.wrapper)
			inheritedSet := make(map[string]bool, len(inherited))
			for _, name := range inherited {
				inheritedSet[name] = true
				if _, ok := tc.delegated[name]; !ok {
					t.Errorf("%v.%s is satisfied by embedding and passes through the replay gate unaudited "+
						"(likely added by an OTel upgrade). Declare it on %T — gating it like Add/Record/Emit, "+
						"or delegating explicitly — or allowlist it in this test with the rationale that makes "+
						"ungated delegation safe.", tc.iface, name, tc.wrapper)
				}
			}
			for name := range tc.delegated {
				if _, ok := tc.iface.MethodByName(name); !ok {
					t.Errorf("allowlist entry %q no longer exists on %v; remove the stale entry", name, tc.iface)
					continue
				}
				if !inheritedSet[name] {
					t.Errorf("allowlist entry %q is now declared on %T; remove the redundant entry", name, tc.wrapper)
				}
			}
		})
	}
}

// grownTracer simulates an OTel minor release adding an emitting method to an
// interface one of the wrappers embeds.
type grownTracer interface {
	trace.Tracer
	// StartDetached stands in for a future context-carrying emission method.
	StartDetached(ctx context.Context, spanName string) (context.Context, trace.Span)
}

type grownTracerImpl struct{ trace.Tracer }

func (g grownTracerImpl) StartDetached(ctx context.Context, spanName string) (context.Context, trace.Span) {
	return g.Tracer.Start(ctx, spanName)
}

// grownTracerWrapper mirrors the replaySafe wrapper pattern: it declares (and
// would gate) Start but is unaware of the newly-grown StartDetached, which the
// embedded field satisfies ungated.
type grownTracerWrapper struct{ grownTracer }

func (w grownTracerWrapper) Start(ctx context.Context, spanName string, opts ...trace.SpanStartOption) (context.Context, trace.Span) {
	return w.grownTracer.Start(ctx, spanName, opts...)
}

// TestSurfaceGuardDetectsSimulatedInterfaceGrowth proves the classifier fires
// on interface growth: the grown method is reported as inherited while the
// declared one is not, so TestReplaySafeWrapperSurface would fail the moment a
// bumped OTel dependency grows a wrapped interface.
func TestSurfaceGuardDetectsSimulatedInterfaceGrowth(t *testing.T) {
	wrapper := grownTracerWrapper{grownTracer: grownTracerImpl{Tracer: tracenoop.NewTracerProvider().Tracer("audit")}}
	inherited := inheritedInterfaceMethods(t, typeOf[grownTracer](), wrapper)
	require.Equal(t, []string{"StartDetached"}, inherited,
		"the grown method must be classified as inherited (unaudited) and the declared Start must not be")
}
